/* The sample agreement behind "Use an example".
 *
 * It exists because a good share of visitors don't have a contract open when
 * they land here, and without something to paste they leave on screen one.
 * It is written to contain the two things the verdict logic leans on: an
 * explicit deliverable list, and a counted limit. */

window.SG = window.SG || {};

SG.EXAMPLE_SCOPE = `WEB DESIGN AGREEMENT — SUMMARY OF WORK

Client: Northbound Coffee Roasters
Designer: independent contractor (the "Designer")
Fee: fixed, invoiced 50% on signature and 50% on delivery.

1. Deliverables
The Designer will produce responsive designs for five (5) pages: Home, Shop,
Product Detail, About, and Contact. Deliverables are Figma files plus an export
of all image assets used.

2. Revisions
The fee includes up to three (3) rounds of revisions across the five agreed page
designs. A round means one consolidated set of feedback from the Client.
Additional rounds are quoted separately and invoiced on completion.

3. Timeline
First designs within 10 working days of receiving brand assets and copy from the
Client. Each revision round is returned within 5 working days of feedback.

4. Not included
Front-end development or CMS implementation, copywriting, photography,
illustration, logo or brand identity work, ongoing maintenance, and any page not
listed in section 1. These can be added by written agreement at the Designer's
current rates.

5. Content
The Client provides all copy and photography. Delays in providing content shift
the timeline by the same number of working days.

6. Approval
Designs are treated as approved if the Client does not respond with feedback
within 10 working days of delivery.`;

